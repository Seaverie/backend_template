-- Mirrors infra/postgres/01-roles.sh: the API never connects as a superuser.
CREATE ROLE tc_owner LOGIN PASSWORD 'owner_test_pw' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE tc_app LOGIN PASSWORD 'app_test_pw' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOINHERIT;
ALTER DATABASE tenantcore OWNER TO tc_owner;
ALTER SCHEMA public OWNER TO tc_owner;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO tc_app;
GRANT CONNECT ON DATABASE tenantcore TO tc_app;
