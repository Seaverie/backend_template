/** Where file bytes live. Keys are generated by the server only; no user input ever reaches a key. */
interface ObjectStore {
    val name: String
    fun put(key: String, source: Path, contentType: String)
    fun open(key: String): InputStream
    fun delete(key: String)
}

class ObjectMissing : ApiException(HttpStatus.NOT_FOUND, "not_found", "The file's contents are missing from storage.")

class LocalStore(dir: String) : ObjectStore {
    override val name = "local"
    private val base: Path = Paths.get(dir).toAbsolutePath().normalize().also { Files.createDirectories(it) }

    private fun resolve(key: String): Path {
        require(Regex("^[a-zA-Z0-9/._-]{1,400}$").matches(key) && ".." !in key) { "bad storage key" }
        return base.resolve(key).normalize().also { require(it.startsWith(base)) { "bad storage key" } }
    }

    override fun put(key: String, source: Path, contentType: String) {
        val target = resolve(key)
        Files.createDirectories(target.parent)
        val tmp = Files.createTempFile(target.parent, ".upload-", ".tmp")
        Files.copy(source, tmp, StandardCopyOption.REPLACE_EXISTING)
        Files.move(tmp, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
    }

    override fun open(key: String): InputStream = resolve(key).let { if (Files.exists(it)) Files.newInputStream(it) else throw ObjectMissing() }

    override fun delete(key: String) { Files.deleteIfExists(resolve(key)) }
}

data class S3Settings(
    @field:Size(max = 300) val endpoint: String = "",
    @field:Size(max = 64) val region: String = "auto",
    @field:Pattern(regexp = "^$|^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$", message = "must be a valid bucket name") val bucket: String = "",
    @field:Size(max = 200) val accessKeyId: String = "",
    @field:Pattern(regexp = "^$|^[a-zA-Z0-9/_-]{1,100}/?$", message = "letters, digits, / _ -") val prefix: String = "",
    /** Needed by MinIO and most self-hosted servers; R2 and AWS work either way. */
    val pathStyle: Boolean = true,
)

class S3Store(private val s: S3Settings, secret: String) : ObjectStore {
    override val name = "s3"
    private val client: S3Client = S3Client.builder()
        .httpClient(UrlConnectionHttpClient.builder().connectionTimeout(Duration.ofSeconds(10)).socketTimeout(Duration.ofSeconds(60)).build())
        .region(Region.of(s.region.ifBlank { "auto" }))
        .credentialsProvider(StaticCredentialsProvider.create(AwsBasicCredentials.create(s.accessKeyId, secret)))
        .serviceConfiguration(S3Configuration.builder().pathStyleAccessEnabled(s.pathStyle).build())
        .apply { if (s.endpoint.isNotBlank()) endpointOverride(URI(s.endpoint)) }
        .build()

    private fun full(key: String) = s.prefix.trim('/').let { if (it.isEmpty()) key else "$it/$key" }

    override fun put(key: String, source: Path, contentType: String) {
        client.putObject(PutObjectRequest.builder().bucket(s.bucket).key(full(key)).contentType(contentType).build(), S3Body.fromFile(source))
    }

    override fun open(key: String): InputStream = try {
        client.getObject(GetObjectRequest.builder().bucket(s.bucket).key(full(key)).build())
    } catch (e: NoSuchKeyException) { throw ObjectMissing() }

    override fun delete(key: String) {
        client.deleteObject(DeleteObjectRequest.builder().bucket(s.bucket).key(full(key)).build())
    }
}

data class StorageSettingsIn(
    @field:Pattern(regexp = "^(local|s3)$", message = "must be local or s3") val driver: String = "local",
    @field:Valid val s3: S3Settings = S3Settings(),
    /** Write-only. Omit to keep the stored secret. */
    @field:Size(max = 200) val s3SecretAccessKey: String? = null,
)
data class StorageSettingsOut(val driver: String, val s3: S3Settings, val s3SecretSet: Boolean, val localDir: String)

/** Chooses the store for new uploads (platform setting) and finds the store an existing file is in. */
@Service
class StorageService(private val settings: PlatformSettingsStore, private val mapper: ObjectMapper, private val props: TcProperties) {
    private val log = LoggerFactory.getLogger(javaClass)
    val local = LocalStore(props.storageDir)
    @Volatile private var s3Cache: Pair<String, S3Store>? = null

    fun settings(): StorageSettingsOut {
        val (v, secret) = settings.read("storage")
        val driver = v["driver"] as? String ?: "local"
        val s3: S3Settings = (v["s3"] as? Map<*, *>)?.let { mapper.convertValue(it) } ?: S3Settings()
        return StorageSettingsOut(driver, s3, !secret.isNullOrEmpty(), local.let { Paths.get(props.storageDir).toAbsolutePath().toString() })
    }

    /** The store new uploads go to. */
    fun current(): ObjectStore = byName(settings().driver)

    fun byName(name: String): ObjectStore = when (name) {
        "local" -> local
        "s3" -> s3()
        else -> error("unknown storage $name")
    }

    private fun s3(): S3Store {
        val (v, secret) = settings.read("storage")
        val s: S3Settings = (v["s3"] as? Map<*, *>)?.let { mapper.convertValue(it) } ?: S3Settings()
        if (s.bucket.isBlank() || s.accessKeyId.isBlank() || secret.isNullOrEmpty())
            throw ApiException(HttpStatus.SERVICE_UNAVAILABLE, "storage_unavailable", "S3 storage is selected but not fully configured.")
        val fingerprint = mapper.writeValueAsString(s) + secret.hashCode()
        s3Cache?.let { if (it.first == fingerprint) return it.second }
        return S3Store(s, secret).also { s3Cache = fingerprint to it }
    }

    fun deleteQuietly(store: String, key: String?) {
        if (key == null) return
        runCatching { byName(store).delete(key) }.onFailure { log.warn("could not delete {} object {}: {}", store, key, it.message) }
    }

    /** Writes, reads back and deletes a small object to prove the configuration works. */
    fun selfTest(store: ObjectStore) {
        val key = "_selftest/${UUID.randomUUID()}"
        val tmp = Files.createTempFile("selftest", ".txt").also { Files.writeString(it, "tenantcore storage test") }
        try {
            store.put(key, tmp, "text/plain")
            store.open(key).use { check(String(it.readAllBytes()) == "tenantcore storage test") { "read back different content" } }
            store.delete(key)
        } finally { Files.deleteIfExists(tmp) }
    }
}

@RestController
@RequestMapping("\${tc.api-prefix}/platform/storage")
class StorageController(
    private val storage: StorageService, private val settings: PlatformSettingsStore, private val db: Db,
    private val audit: Audit, private val mapper: ObjectMapper,
) {
    @GetMapping
    fun get() = storage.settings()

    /** Switches where new uploads go. Existing files stay where they are and keep working. */
    @PutMapping
    fun put(@Valid @RequestBody body: StorageSettingsIn): StorageSettingsOut {
        if (body.driver == "s3") {
            if (body.s3.bucket.isBlank() || body.s3.accessKeyId.isBlank()) throw Invalid("S3 storage needs a bucket and an access key id.")
            if (body.s3.endpoint.isNotBlank()) {
                val u = runCatching { URI(body.s3.endpoint) }.getOrNull()
                if (u == null || u.scheme !in setOf("https", "http") || u.host.isNullOrBlank()) throw Invalid("The S3 endpoint must be an http(s) URL.")
            }
            val secret = body.s3SecretAccessKey ?: settings.read("storage").second
            if (secret.isNullOrEmpty()) throw Invalid("Enter the secret access key.")
            // Prove the new configuration works before any upload depends on it.
            runCatching { storage.selfTest(S3Store(body.s3, secret)) }
                .onFailure { throw Invalid("Could not use that bucket: ${it.message?.take(300)}") }
        }
        // Switching back to local disk keeps the S3 details: files already in S3 are still read from there.
        val s3Block: Any? = if (body.driver == "local" && body.s3.bucket.isBlank()) settings.read("storage").first["s3"]
            else mapper.convertValue<Map<String, Any?>>(body.s3)
        db.platform { j ->
            settings.write(j, "storage", mapOf("driver" to body.driver, "s3" to s3Block), body.s3SecretAccessKey)
            audit.record(j, null, "platform_settings.update", "platform_settings", "storage", mapOf("driver" to body.driver))
        }
        return storage.settings()
    }

    @PostMapping("/test")
    fun test(): Map<String, Any> {
        val store = storage.current()
        return runCatching { storage.selfTest(store); mapOf("ok" to true, "driver" to store.name) }
            .getOrElse { mapOf("ok" to false, "driver" to store.name, "error" to (it.message ?: it.javaClass.simpleName).take(300)) }
    }
}
