OLD_RESOURCE_RE = r"^(data\.[a-z][a-z0-9_]{0,62}|users|roles|api_keys|audit_logs)$"
NEW_RESOURCE_RE = (
    r"^(data\.[a-z][a-z0-9_]{0,62}|users|roles|api_keys|audit_logs|settings|analytics|"
    r"products|inventory|purchasing|orders|rma|payments|maps)$"
)


def _q(ident: str) -> str:
    import re
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", ident):
        raise ValueError(f"invalid identifier: {ident!r}")
    return '"' + ident + '"'


def _security_upgrade() -> None:
    app = _q(APP_ROLE)
    for t, privs in TENANT_TABLES:
        op.execute(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {t} FORCE ROW LEVEL SECURITY")
        op.execute(f"""
            CREATE POLICY tenant_isolation ON {t} AS PERMISSIVE FOR ALL TO PUBLIC
            USING (tenant_id = app_current_tenant_id())
            WITH CHECK (tenant_id = app_current_tenant_id())
        """)
        op.execute(f"GRANT {privs} ON {t} TO {app}")
    op.execute(f"GRANT USAGE ON SEQUENCE stock_movements_id_seq TO {app}")

    op.execute("""
        CREATE FUNCTION append_only_guard() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
          RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
        END $$
    """)
    for t in APPEND_ONLY:
        op.execute(f"""
            CREATE TRIGGER {t}_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON {t}
            FOR EACH STATEMENT EXECUTE FUNCTION append_only_guard()
        """)

    # Inbound payment webhooks identify only the gateway; this SELECT-only policy exposes exactly the
    # gateway being verified, so the handler can learn its tenant before entering tenant context.
    op.execute("""
        CREATE POLICY gateway_lookup ON app_payment_gateways AS PERMISSIVE FOR SELECT TO PUBLIC
        USING (id::text = nullif(current_setting('app.gateway_lookup', true), ''))
    """)

    # Dedicated tenant databases: control plane. The owning tenant may read its row (request routing);
    # only platform transactions may write.
    op.execute("ALTER TABLE app_tenant_databases ENABLE ROW LEVEL SECURITY")
    op.execute("ALTER TABLE app_tenant_databases FORCE ROW LEVEL SECURITY")
    op.execute("""
        CREATE POLICY tenant_db_read ON app_tenant_databases FOR SELECT TO PUBLIC
        USING (tenant_id = app_current_tenant_id() OR app_is_platform())
    """)
    for cmd in ("INSERT", "UPDATE", "DELETE"):
        clause = "WITH CHECK (app_is_platform())" if cmd == "INSERT" else "USING (app_is_platform())"
        op.execute(f"CREATE POLICY tenant_db_{cmd.lower()} ON app_tenant_databases FOR {cmd} TO PUBLIC {clause}")
    op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON app_tenant_databases TO {app}")

    op.execute("ALTER TABLE app_permissions DROP CONSTRAINT ck_app_permissions_resource_format")
    op.execute(f"ALTER TABLE app_permissions ADD CONSTRAINT ck_app_permissions_resource_format CHECK (resource ~ '{NEW_RESOURCE_RE}')")


def _security_downgrade() -> None:
    # The owner is subject to FORCE RLS; lift it briefly to remove permissions the old constraint rejects.
    op.execute("ALTER TABLE app_permissions NO FORCE ROW LEVEL SECURITY")
    op.execute(f"DELETE FROM app_permissions WHERE resource !~ '{OLD_RESOURCE_RE}'")  # noqa: S608 - constant
    op.execute("ALTER TABLE app_permissions FORCE ROW LEVEL SECURITY")
    op.execute("ALTER TABLE app_permissions DROP CONSTRAINT ck_app_permissions_resource_format")
    op.execute(f"ALTER TABLE app_permissions ADD CONSTRAINT ck_app_permissions_resource_format CHECK (resource ~ '{OLD_RESOURCE_RE}')")
